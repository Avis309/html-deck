export function storedLang() {
  try { return localStorage.getItem(LANG_KEY) || 'vi'; } catch { return 'vi'; }
}
export function layerName(lang, tag) {
  return (LAYER_NAMES[lang] && LAYER_NAMES[lang][tag]) || (LAYER_NAMES.vi && LAYER_NAMES.vi[tag]) || tag;
}
export function translate(lang, key, fallback = '') {
  return (I18N[lang] && I18N[lang][key]) || (I18N.vi && I18N.vi[key]) || fallback || key;
}
// Toasts are written in Vietnamese at the call site; EN/ZH are matched by pattern.
export function translateToastFor(lang, msg) {
  if (typeof msg !== 'string') return String(msg);
  const table = lang === 'en' ? TOAST_EN_PATTERNS : lang === 'zh' ? TOAST_ZH_PATTERNS : null;
  if (table) for (const [pattern, rep] of table) if (pattern.test(msg)) return msg.replace(pattern, rep);
  return msg;
}
